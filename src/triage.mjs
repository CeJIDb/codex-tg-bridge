// Якорим внешние паттерны на полное сообщение (с хвостовой пунктуацией).
const IMPORTED = DEEPPAVLOV.flatMap(({ raw, reply }) =>
  raw.map((p) => ({ re: new RegExp(`^(?:${p})[\\s!.?,]*$`, "u"), reply })),
);

const PATTERNS = [...MANUAL, ...IMPORTED];

function normalize(s) {
  return s.trim().toLowerCase().replace(/ё/g, "е");
}

export function triage(text) {
  const n = normalize(text);
  if (!/[\p{L}\p{N}]/u.test(n)) {
    return "Сформулируй вопрос текстом.";
  }
  for (const { re, reply } of PATTERNS) {
    if (re.test(n)) return reply;
  }
  return null;
}
