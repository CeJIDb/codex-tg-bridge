let pass = 0;
const failures = [];

for (const text of CHITCHAT) {
  const got = triage(text);
  if (got !== null) {
    pass++;
  } else {
    failures.push({ kind: "chitchat", text, got: "null (ожидалась заглушка)" });
  }
}
for (const text of NORMATIVE) {
  const got = triage(text);
  if (got === null) {
    pass++;
  } else {
    failures.push({ kind: "normative", text, got: `«${got}» (ожидался null)` });
  }
}

const total = CHITCHAT.length + NORMATIVE.length;
console.log(`\nПройдено: ${pass}/${total}`);
if (failures.length > 0) {
  console.log(`\nПровалов: ${failures.length}\n`);
  const byKind = { chitchat: [], normative: [] };
  for (const f of failures) byKind[f.kind].push(f);
  if (byKind.chitchat.length) {
    console.log("Болтовня, не попавшая в триаж (нужно расширять паттерны):");
    for (const f of byKind.chitchat) console.log(`  «${f.text}»`);
  }
  if (byKind.normative.length) {
    console.log("\nНормативные вопросы, ложно попавшие в триаж (нужно сузить паттерны):");
    for (const f of byKind.normative) console.log(`  «${f.text}»  →  ${f.got}`);
  }
  process.exit(1);
}
process.exit(0);
